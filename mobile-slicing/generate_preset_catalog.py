#!/usr/bin/env python3
"""Generate the Android/native offline catalog from versioned repository profiles.
No timestamps/network. --check verifies both committed JSON and embedded bytes.
The generic machine is an explicit offline-only curated profile, not a printer claim.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HERE = Path(__file__).resolve().parent
META = {'type', 'name', 'inherits', 'from', 'setting_id', 'filament_id', 'instantiation',
        'renamed_from', 'compatible_printers', 'compatible_printers_condition', 'description'}

def digest(path):
    # Git text blobs use LF; checkout CRLF must not change the catalog identity.
    content = path.read_bytes().replace(b'\r\n', b'\n')
    return {'path': path.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(content).hexdigest(), 'hashFormat': 'utf8-lf'}

def resolve(path, stack=()):
    if path in stack:
        raise ValueError('Cyclic preset inheritance: ' + str(path))
    value = json.loads(path.read_text(encoding='utf-8'))
    merged, refs = {}, []
    if value.get('inherits'):
        base = value['inherits']
        candidates = [p for p in (ROOT / 'resources/profiles/OrcaFilamentLibrary/filament').rglob('*.json')
                      if p.stem == base]
        if len(candidates) != 1:
            raise ValueError('Missing/ambiguous inherits: ' + base)
        merged, refs = resolve(candidates[0], stack + (path,))
    merged.update({k: v for k, v in value.items() if k not in META})
    return merged, refs + [digest(path)]

def generate():
    schema = ROOT / 'src/libslic3r/PrintConfig.cpp'
    known_keys = set(re.findall(r'\badd\s*\(\s*"([^"]+)"', schema.read_text(encoding='utf-8')))
    materials = []
    for name, ident in [('PLA', 'generic/pla'), ('PETG', 'generic/petg')]:
        src = ROOT / ('resources/profiles/OrcaFilamentLibrary/filament/Generic ' + name + ' @System.json')
        config, refs = resolve(src)
        unsupported = {k: config.pop(k) for k in list(config) if k not in known_keys}
        config['filament_settings_id'] = ['Generic ' + name + ' @System']
        materials.append({'id': ident, 'name': 'Generic ' + name,
                          'summary': ('Repository Generic ' + name + '; nozzle ' + config['nozzle_temperature'][0] +
                                      ' C, first layer ' + config['nozzle_temperature_initial_layer'][0] +
                                      ' C; textured bed ' + config['textured_plate_temp'][0] +
                                      ' C; density ' + config['filament_density'][0] +
                                      ' g/cm3; flow ratio ' + config['filament_flow_ratio'][0] +
                                      '. Sources: ' + ', '.join(r['path'] for r in refs) + '. Currency unspecified. Unsupported legacy source options not applied: ' + ', '.join(sorted(unsupported))),
                          'config': config, 'sourceRefs': refs, 'schemaSourceRef': digest(schema), 'unsupportedSourceOptions': unsupported})
    curated = HERE / 'offline-device-v1.json'
    device = json.loads(curated.read_text(encoding='utf-8'))
    device['sourceRefs'] = [digest(curated)] + materials[0]['sourceRefs']
    device['defaultMaterialId'] = 'generic/pla'
    device['schemaSourceRef'] = digest(schema)
    device['unsupportedSourceOptions'] = materials[0]['unsupportedSourceOptions']
    device['config'].update(materials[0]['config'])
    catalog = {'version': 'p1-offline-v1',
               'devices': [{'id': 'source/current', 'name': 'Source / current project',
                            'summary': 'Restore the original embedded machine, material and process profile.', 'restoreSource': True, 'available': False, 'reason': 'Refresh this project to capture the original source profile before restoring it.'}, device],
               'materials': [{'id': 'source/current', 'name': 'Source material',
                              'summary': 'Restore original source material options, leaving the machine/process unchanged.', 'restoreSource': True, 'available': False, 'reason': 'Refresh this project to capture the original source profile before restoring it.'}] + materials,
               'sourceRefs': [digest(curated), digest(schema)] + list({r['path']: r for m in materials for r in m['sourceRefs']}.values())}
    payload = json.dumps(catalog, ensure_ascii=False, indent=2) + '\n'
    header = '#pragma once\n// Generated by mobile-slicing/generate_preset_catalog.py; do not edit.\nnamespace orca::mobile::slicing {\ninline constexpr char kOfflinePresetCatalog[] = R"ORCAPRESET(' + payload + ')ORCAPRESET";\n}\n'
    return {HERE / 'preset-catalog-v1.json': payload, ROOT / 'src/orca_mobile_slicing_sdk/preset_catalog.generated.hpp': header}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    for path, content in generate().items():
        if options.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('Stale catalog: ' + str(path))
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
        print(('Verified ' if options.check else 'Generated ') + path.relative_to(ROOT).as_posix())

if __name__ == '__main__':
    main()
